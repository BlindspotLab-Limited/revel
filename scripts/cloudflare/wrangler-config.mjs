/**
 * Builds the deploy-time Wrangler config from the committed wrangler.jsonc.
 *
 * The committed file contains no account-specific identifiers. This module
 * adds the Hyperdrive binding from the CLOUDFLARE_HYPERDRIVE_ID build
 * variable and writes the result to the git-ignored wrangler.deploy.jsonc,
 * which both `opennextjs-cloudflare build` and `deploy` are pointed at.
 */
import { readFileSync, writeFileSync } from "node:fs";
import path from "node:path";

export const ROOT = path.resolve(import.meta.dirname, "..", "..");
export const BASE_CONFIG = path.join(ROOT, "wrangler.jsonc");
export const DEPLOY_CONFIG = path.join(ROOT, "wrangler.deploy.jsonc");

const HYPERDRIVE_ID_PATTERN = /^[0-9a-f]{32}$/i;

/** Placeholder accepted only for local `wrangler dev` / preview runs. */
export const LOCAL_HYPERDRIVE_ID = "00000000000000000000000000000000";

/** Strip // and /* *\/ comments and trailing commas, respecting strings. */
export function parseJsonc(text) {
  let out = "";
  let inString = false;
  for (let i = 0; i < text.length; i++) {
    const ch = text[i];
    const next = text[i + 1];
    if (inString) {
      out += ch;
      if (ch === "\\") {
        out += next ?? "";
        i++;
      } else if (ch === '"') {
        inString = false;
      }
      continue;
    }
    if (ch === '"') {
      inString = true;
      out += ch;
    } else if (ch === "/" && next === "/") {
      while (i < text.length && text[i] !== "\n") i++;
      out += "\n";
    } else if (ch === "/" && next === "*") {
      i += 2;
      while (i < text.length && !(text[i] === "*" && text[i + 1] === "/")) i++;
      i++;
    } else {
      out += ch;
    }
  }
  return JSON.parse(out.replace(/,(\s*[}\]])/g, "$1"));
}

export function isWorkersCi(env = process.env) {
  return env.WORKERS_CI === "1";
}

/**
 * Resolve the Hyperdrive id to bind, or throw with an actionable message.
 * - Workers Builds (WORKERS_CI=1): CLOUDFLARE_HYPERDRIVE_ID is mandatory.
 * - Local: the placeholder id is used when a local connection string is
 *   provided (CLOUDFLARE_HYPERDRIVE_LOCAL_CONNECTION_STRING_HYPERDRIVE),
 *   otherwise the binding is omitted.
 */
export function resolveHyperdriveId(env = process.env) {
  const raw = env.CLOUDFLARE_HYPERDRIVE_ID?.trim();

  if (raw) {
    if (!HYPERDRIVE_ID_PATTERN.test(raw)) {
      throw new Error(
        "CLOUDFLARE_HYPERDRIVE_ID must be the 32-character Hyperdrive configuration ID " +
          "(Cloudflare dashboard → Storage & databases → Hyperdrive → your config). " +
          "Do not paste the database connection string here."
      );
    }
    return raw.toLowerCase();
  }

  if (isWorkersCi(env)) {
    throw new Error(
      "CLOUDFLARE_HYPERDRIVE_ID is not set. Add it under Workers & Pages → revel → " +
        "Settings → Build → Variables and secrets, then retry the build. " +
        "See docs/cloudflare-deployment.md (step 'Build variables')."
    );
  }

  return env.CLOUDFLARE_HYPERDRIVE_LOCAL_CONNECTION_STRING_HYPERDRIVE
    ? LOCAL_HYPERDRIVE_ID
    : null;
}

export function buildDeployConfig(baseText, hyperdriveId) {
  const config = parseJsonc(baseText);
  if (config.hyperdrive) {
    throw new Error(
      "wrangler.jsonc must not declare `hyperdrive`; its id is injected from CLOUDFLARE_HYPERDRIVE_ID."
    );
  }
  if (hyperdriveId) {
    config.hyperdrive = [{ binding: "HYPERDRIVE", id: hyperdriveId }];
  }
  return config;
}

export function writeDeployConfig(env = process.env) {
  const hyperdriveId = resolveHyperdriveId(env);
  const config = buildDeployConfig(readFileSync(BASE_CONFIG, "utf8"), hyperdriveId);
  writeFileSync(
    DEPLOY_CONFIG,
    "// GENERATED by scripts/cloudflare/build.mjs from wrangler.jsonc — do not edit or commit.\n" +
      JSON.stringify(config, null, 2) +
      "\n"
  );
  return { config, hyperdriveId };
}
